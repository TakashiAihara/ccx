func TestStepDoesNotRepeatAnUnansweredBeat(t *testing.T) {
	// Delivered, but the answer never came (the request failed).
	tr := rec("user", "10:00:00", human) + rec("assistant", "10:00:05", reply) + rec("user", "10:50:06", beat)
	h, pushes, _ := fixture(t, tr, at("10:51:06"))
	var sent time.Time
	h.step(&sent)
	if *pushes != 0 {
		t.Fatalf("a minute after an unanswered beat: pushes=%d, want 0", *pushes)
	}
	// An interval after it the cache is gone: the last request that answered was
	// 10:00:00. The failed heartbeat read nothing, so it does not keep it alive.
	// Past turnStart it no longer looks like a running turn, and it is still not
	// sent again: the next is due an interval after the unanswered one.
	h.Now = func() time.Time { return at("10:56:06") }
	h.step(&sent)
	if *pushes != 0 {
		t.Fatalf("6 minutes after an unanswered beat, cache warm: pushes=%d, want 0", *pushes)
	}
	// step says wait an interval rather than a poll, as for a running turn (Run
	// still wakes every poll, so a declaration change is seen within a minute).
	h.Now = func() time.Time { return at("11:40:06") }
	if wait := h.step(&sent); *pushes != 0 || wait != h.Interval {
		t.Fatalf("after a failed beat, past the TTL: pushes=%d wait=%v, want 0 and %v", *pushes, wait, h.Interval)
	}
}

