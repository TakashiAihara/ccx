// A synthetic API-error reply ("Prompt is too long") read no cache, so it is not
// an answer: the cache counts from the last real one and expires on time, and a
// session stuck failing is not woken every 50 minutes.
func TestStepIgnoresAPIErrorReplies(t *testing.T) {
	tr := rec("user", "10:00:00", human) + rec("assistant", "10:00:05", reply) +
		rec("user", "10:40:00", human) + rec("assistant", "10:40:01", apiError)
	// 11:30:02: counted from the error reply (10:40:01) this would be due.
	h, pushes, _ := fixture(t, tr, at("11:30:02"))
	var sent time.Time
	h.step(&sent)
	if *pushes != 0 {
		t.Errorf("50m after the failed request, 90m after the last answer: pushes=%d, want 0", *pushes)
	}
}

// One response is often several assistant records (thinking, then text). A later
// record's parent is the earlier one; it answers the same request.
func TestStepTracesAResponseSplitAcrossRecords(t *testing.T) {
	thinking := `,"message":{"role":"assistant","content":[{"type":"thinking","thinking":"..."}]}`
	tr := rec("user", "10:00:00", human) + rec("assistant", "10:00:30", thinking) + rec("assistant", "10:12:00", reply)
	h, pushes, _ := fixture(t, tr, at("10:50:00"))
	var sent time.Time
	h.step(&sent)
	if *pushes != 1 {
		t.Errorf("50m after the prompt the split response answered: pushes=%d, want 1", *pushes)
	}
}

// The response's parentUuid decides which input it answers, not which user
// record came last: a later record that is not its parent (a sibling, a record
// written out of order) does not move the request start.
func TestStepFollowsTheParentNotTheLatestInput(t *testing.T) {
	tr := `{"type":"user","uuid":"p1","timestamp":"2026-09-23T10:00:00.000Z"` + human + "}\n" +
		`{"type":"user","uuid":"p2","timestamp":"2026-09-23T10:20:00.000Z"` + crossMsg + "}\n" +
		`{"type":"assistant","uuid":"a1","parentUuid":"p1","timestamp":"2026-09-23T10:20:05.000Z"` + reply + "}\n"
	h, pushes, _ := fixture(t, tr, at("10:50:00"))
	var sent time.Time
	h.step(&sent)
	if *pushes != 1 {
		t.Errorf("50m after the parent prompt: pushes=%d, want 1", *pushes)
	}
}

// A tool call left without a result (a rewind, a crash) does not stop keepalive
// for good: once a later request is answered, it is dropped.
func TestStepDropsAnAbandonedToolCall(t *testing.T) {
	tr := rec("user", "10:00:00", human) + rec("assistant", "10:00:05", toolUse) +
		rec("user", "10:20:00", human) + rec("assistant", "10:20:05", reply)
	h, pushes, _ := fixture(t, tr, at("11:10:00"))
	var sent time.Time
	h.step(&sent)
	if *pushes != 1 {
		t.Errorf("50m after a later answered prompt: pushes=%d, want 1", *pushes)
	}
}
